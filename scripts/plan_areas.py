"""Generate config/areas.toml: the intake areas inside each Caltrain station's 25-minute walk zone.

Samples points ~500 m apart inside each zone, reverse-geocodes them with Nominatim (reference data,
1 request per second, generic User-Agent), and records which ZIP codes and cities the zones touch.
Each source then runs on its smallest efficient unit: ZIP (Zillow, Apartments.com, Craigslist),
city (Furnished Finder), or the zone's bounding box (Airbnb).

  env -u PYTHONPATH uv run python scripts/plan_areas.py
"""

from __future__ import annotations

import json
import math
import sys
import time
from collections import defaultdict
from pathlib import Path

import httpx

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from aptfinder import settings  # noqa: E402
from aptfinder.config import load_points  # noqa: E402

WALK_MIN = 25
RADIUS_KM = WALK_MIN * 80 / 1.3 / 1000  # estimator: 80 m/min walking, 1.3 detour factor -> ~1.54 km
STEP_KM = 0.5
# Work order: station groups (chunks). Mountain View + San Antonio first (user's choice).
CHUNKS = [
    ("mountain_view", ["Mountain View", "San Antonio"]),
    ("palo_alto", ["Palo Alto", "California Ave", "Menlo Park"]),
    ("redwood_city", ["Redwood City"]),
    ("sunnyvale", ["Sunnyvale", "Lawrence"]),
]
CACHE = settings.DATA_DIR / "reverse_geocode_cache.json"


def zone_points(lat: float, lon: float):
    dlat = STEP_KM / 111.0
    dlon = STEP_KM / (111.0 * math.cos(math.radians(lat)))
    n = int(RADIUS_KM / STEP_KM) + 1
    for i in range(-n, n + 1):
        for j in range(-n, n + 1):
            if math.hypot(i * STEP_KM, j * STEP_KM) <= RADIUS_KM:
                yield (round(lat + i * dlat, 5), round(lon + j * dlon, 5))


def main() -> None:
    stations = {p.name: p for p in load_points()["caltrain_stations"]}
    cache = json.loads(CACHE.read_text()) if CACHE.exists() else {}
    client = httpx.Client(timeout=30, headers={"User-Agent": "apartment-finder/0.1 (personal research script)"})
    zips: dict[str, dict] = {}
    cities: dict[str, set] = defaultdict(set)
    boxes = []
    for chunk, names in CHUNKS:
        for name in names:
            st = stations[name]
            for lat, lon in zone_points(st.lat, st.lon):
                key = f"{lat},{lon}"
                if key not in cache:
                    r = client.get("https://nominatim.openstreetmap.org/reverse",
                                   params={"format": "json", "lat": lat, "lon": lon, "zoom": 18,
                                           "addressdetails": 1})
                    time.sleep(1.1)
                    cache[key] = (r.json() or {}).get("address", {}) if r.status_code == 200 else {}
                    CACHE.parent.mkdir(parents=True, exist_ok=True)
                    CACHE.write_text(json.dumps(cache))
                a = cache[key]
                pc = (a.get("postcode") or "")[:5]
                city = a.get("city") or a.get("town") or a.get("village") or a.get("hamlet")
                if pc.isdigit():
                    z = zips.setdefault(pc, {"chunks": [], "stations": set(), "cities": defaultdict(int), "n": 0})
                    if chunk not in z["chunks"]:
                        z["chunks"].append(chunk)
                    z["stations"].add(name)
                    z["n"] += 1
                    if city:
                        z["cities"][city] += 1
                if city:
                    cities[city].add(chunk)
            dlat = RADIUS_KM / 111.0
            dlon = RADIUS_KM / (111.0 * math.cos(math.radians(st.lat)))
            boxes.append((chunk, name, [round(st.lat - dlat, 4), round(st.lon - dlon, 4),
                                        round(st.lat + dlat, 4), round(st.lon + dlon, 4)]))
            print(f"{chunk:14s} {name:15s} done")

    order = {c: i for i, (c, _) in enumerate(CHUNKS)}
    lines = [
        "# Intake areas: everything inside each Caltrain station's 25-minute walk zone (radius "
        f"{RADIUS_KM:.2f} km).",
        "# Generated by scripts/plan_areas.py (Nominatim reverse geocoding, ~500 m sample grid). Edit freely.",
        "# Chunks are worked in this order; coverage per source and area: `aptf-intake coverage`.",
        "# `samples` = how many grid points fell in that ZIP (small numbers mean the zone only clips it).",
        "",
        "chunks = [" + ", ".join(f'"{c}"' for c, _ in CHUNKS) + "]",
        "# Chunks being worked now. Places outside them are marked TODO in the dashboard and get no paid routing.",
        f'active = ["{CHUNKS[0][0]}"]',
        f"radius_km = {RADIUS_KM:.2f}",
        "chunk_stations = { " + ", ".join(f'{c} = [' + ", ".join(f'"{n}"' for n in ns) + "]" for c, ns in CHUNKS)
        + " }",
        "",
    ]
    for code, z in sorted(zips.items(), key=lambda kv: (min(order[c] for c in kv[1]["chunks"]), -kv[1]["n"])):
        city = max(z["cities"], key=z["cities"].get) if z["cities"] else ""
        lines += ["[[zip]]", f'code = "{code}"', f'city = "{city}"',
                  "chunks = [" + ", ".join(f'"{c}"' for c in z["chunks"]) + "]",
                  "stations = [" + ", ".join(f'"{s}"' for s in sorted(z["stations"])) + "]",
                  f"samples = {z['n']}", ""]
    for city, chs in sorted(cities.items(), key=lambda kv: min(order[c] for c in kv[1])):
        lines += ["[[city]]", f'name = "{city}"',
                  "chunks = [" + ", ".join(f'"{c}"' for c in sorted(chs, key=order.get)) + "]", ""]
    for chunk, name, bbox in boxes:
        lines += ["[[box]]", f'id = "{name.lower().replace(" ", "_")}"', f'chunk = "{chunk}"',
                  f'station = "{name}"', f"bbox = {bbox}  # south, west, north, east", ""]
    (settings.CONFIG_DIR / "areas.toml").write_text("\n".join(lines))
    print(f"{len(zips)} zips, {len(cities)} cities, {len(boxes)} boxes -> config/areas.toml")


if __name__ == "__main__":
    main()
